package ru.taska.util;

/**
 * Глобальный контракт для валидаторов в auth микросервисе.
 *
 * <p>Определяет единый способ валидации объектов различных типов.
 * Каждая реализация отвечает за валидацию конкретного типа объектов
 * в соответствии с бизнес-правилами.
 *
 * @param <T> тип объекта для валидации
 */
public interface Validator<T> {

    /**
     * Валидация переданного объекта
     * @param obj объект для валидации
     * @throws RuntimeException если объект не прошел валидацию
     */
    void validate(T obj);
}
