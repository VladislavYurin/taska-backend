package ru.taska.entity;

/**
 * Тип учётных данных пользователя.
 *
 * <p>Определяет способ аутентификации в системе.</p>
 */
public enum CredentialType {

    /**
     * Парольная аутентификация.
     */
    PASSWORD,

    /**
     * OAuth 2.0 (авторизация через внешний сервис).
     */
    OAUTH,

    /**
     * OpenID Connect (аутентификация через внешний провайдер).
     */
    OIDC,

    /**
     * SAML-аутентификация (корпоративные SSO-системы).
     */
    SAML,

    /**
     * API-токен для машинного доступа.
     */
    API_TOKEN,

    /**
     * WebAuthn (аппаратные ключи, биометрия).
     */
    WEBAUTHN
}