package ru.taska.entity;

/**
 * Статус жизненного цикла пользователя.
 *
 * <p>Определяет возможность аутентификации и использования системы.</p>
 */
public enum UserStatus {

    /**
     * Пользователь активирован и может входить в систему.
     */
    ACTIVE,

    /**
     * Пользователь временно или постоянно заблокирован.
     */
    BLOCKED,

    /**
     * Пользователь создан, но ещё не завершил активацию (не установил пароль).
     */
    INVITED
}