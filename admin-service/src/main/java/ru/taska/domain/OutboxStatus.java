package ru.taska.domain;

/**
 * Технический статус outbox-события.
 * <p>
 * Для административного retry допускаются:
 * <ul>
 *     <li>{@link #FAILED};</li>
 *     <li>{@link #PROCESSING}, если событие считается зависшим.</li>
 * </ul>
 * Статусы {@link #NEW} и {@link #PUBLISHED} повторно отправлять
 * через административную операцию запрещено.
 */
public enum OutboxStatus {

    /**
     * Событие ожидает обработки publisher-ом.
     */
    NEW,

    /**
     * Событие находится в процессе обработки.
     */
    PROCESSING,

    /**
     * Событие успешно опубликовано.
     */
    PUBLISHED,

    /**
     * Обработка или публикация события завершилась ошибкой.
     */
    FAILED
}