package ru.taska.config.props;

/**
 * Тип маскировки для sensitive колонок.
 */
public enum MaskType {

    /** Полная маскировка: значение заменяется на "***". */
    MASK_FULL,

    /** Частичная маскировка: видны первый и последний символы, остальное заменяется на '*'. */
    MASK_PARTIAL,

    /** Колонка полностью скрывается из ответа. */
    HIDE
}
