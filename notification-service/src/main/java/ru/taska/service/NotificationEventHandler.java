package ru.taska.service;

import ru.taska.event.TaskaEvent;
import reactor.core.publisher.Mono;

/**
 * Обработчик доменных событий Kafka, порождающий уведомления пользователям.
 *
 * <p>Реализация должна обеспечивать идемпотентность: повторная доставка
 * одного и того же события (одинаковый {@code eventId}) не должна приводить
 * к повторному созданию уведомлений или повторной отправке email.</p>
 *
 * <p>Ожидаемые побочные эффекты обработки события:</p>
 * <ul>
 *     <li>сохранение уведомлений, построенных по событию;</li>
 *     <li>отправка email-уведомлений (если включена у пользователя);</li>
 *     <li>фиксация факта обработки события для дедупликации.</li>
 * </ul>
 */
public interface NotificationEventHandler {

    /**
     * Обрабатывает одно доменное событие.
     *
     * <p>Если событие или его {@code id} равны {@code null}, обработка
     * пропускается без побочных эффектов. Если событие уже было обработано
     * ранее, метод завершается успешно, не создавая дублей.</p>
     *
     * @param event доменное событие из Kafka.
     * @return {@link Mono}, сигнализирующий о завершении обработки.
     */
    Mono<Void> handle(TaskaEvent event);
}
